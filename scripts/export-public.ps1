<#
.SYNOPSIS
  Produce a public-safe copy of this repo into a directory you choose.

.DESCRIPTION
  A public copy is an EXPORT, never a visibility flip on this repo. Two reasons:

    1. Git history. This repo's history contains files that were later deleted,
       including a project session note describing a payments system and its
       then-unfixed defects. Scrubbing the working tree does nothing about that:
       anyone can recover it from an old commit. A fresh repo has no such history.

    2. Some files here are legitimately machine-specific (generated tool configs,
       absolute MCP binary paths). They are not "fixable", only excludable.

  What this script does NOT do: create a repo, commit, or push. It writes a
  directory and prints what it excluded, so you can read the tree before deciding.

  NOTE: this file is deliberately ASCII-only. Windows PowerShell reads .ps1 as
  ANSI unless there is a BOM, so a stray em-dash becomes mojibake and the script
  fails to parse.

.EXAMPLE
  ./scripts/export-public.ps1 -Destination C:/dev/agent-orchestration-public
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$Destination,
    # The public repo's clone URL. The README ships install instructions, and
    # left alone they point at the PRIVATE repo, which nobody else can clone.
    [string]$PublicRepoUrl,
    [switch]$Force
)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot

# --- what never goes public -------------------------------------------------
# Machine- or project-specific by nature. Each entry is a reason, not a rule of
# thumb: if you add something here, say why.
# Matched against the forward-slash relative path. Anchored deliberately: an
# earlier version used a bare '.git' substring and silently dropped .gitignore
# and .gitignore-additions.md, both of which SHOULD ship.
$excludePathPrefixes = @(
    '.git/',                   # history is the whole reason this is an export
    '.github/',                # workflows may reference private infrastructure
    'docs/'                    # internal design notes (specs/plans/reviews), not shipped product
)
$excludeExactPaths = @(
    'codex/config.toml',       # generated by Codex: content-hashed paths, CODEX_HOME
    'gemini/settings.json',    # absolute path to a locally-installed MCP binary
    'scripts/install-hooks.ps1',              # PRIVATE installer (pins private remote); public ships its own, below
    'scripts/hooks/public-install-hooks.ps1', # source for the public installer; placed as scripts/install-hooks.ps1
    'scripts/hooks/private-pre-push'          # PRIVATE push-guard body (names the private repo); never public
)
$excludeNamePatterns = @(
    '*.local.md',              # project runbooks + incident detail (by convention)
    '*.local.txt',             # e.g. the scrub list, which names what it scrubs
    '.env', '.env.*'           # belt and braces; also caught by $secretIndicators
)

# Matching these is a hard STOP, not an exclusion. They should never have been in
# the repo at all, so their presence means something upstream broke.
$secretIndicators = @('notify.env', 'sa-key.json', '*.pem', '*.p12', 'id_rsa', '.npmrc')

# Refresh the destination WITHOUT touching its .git. The public repo is a
# long-lived repo with its own history that gets updated periodically; blowing
# away its .git would destroy that history on the second run and force a
# push --force. So: clear the tracked content, keep the repository.
$destIsRepo = $false
if (Test-Path $Destination) {
    $destIsRepo = Test-Path (Join-Path $Destination '.git')
    if (-not $Force -and -not $destIsRepo) {
        throw "$Destination already exists and is not a git repo. Re-run with -Force to overwrite."
    }
    Get-ChildItem -Path $Destination -Force |
        Where-Object { $_.Name -ne '.git' } |
        ForEach-Object { Remove-Item -Recurse -Force $_.FullName }
    if ($destIsRepo) {
        Write-Host "Refreshing existing repo at $Destination (its .git and history are preserved)."
    }
} else {
    New-Item -ItemType Directory -Path $Destination -Force | Out-Null
}

$excluded = New-Object System.Collections.Generic.List[string]
$copied = 0

# Export what git TRACKS, not what happens to be on disk. Walking the filesystem
# would sweep in gitignored files that live in the working directory (stray .env,
# local scratch, editor state) and publish them.
Push-Location $repo
$tracked = (git ls-files) -split "`n" | Where-Object { $_.Trim() }
Pop-Location
if (-not $tracked) { throw "git ls-files returned nothing - is $repo a git repository?" }

$tracked | ForEach-Object {
    $relUnix = $_.Trim() -replace '\\', '/'
    $rel = $relUnix -replace '/', [IO.Path]::DirectorySeparatorChar
    $full = Join-Path $repo $rel
    if (-not (Test-Path $full)) { return }
    $_ = Get-Item -LiteralPath $full

    foreach ($bad in $secretIndicators) {
        if ($_.Name -like $bad) {
            throw "REFUSING TO EXPORT: '$relUnix' looks like a credential file. It should not be in this repo at all. Investigate before exporting."
        }
    }

    $skip = $false
    foreach ($p in $excludePathPrefixes) { if ($relUnix.StartsWith($p)) { $skip = $true; break } }
    if (-not $skip) {
        foreach ($p in $excludeExactPaths) { if ($relUnix -eq $p) { $skip = $true; break } }
    }
    if (-not $skip) {
        foreach ($p in $excludeNamePatterns) { if ($_.Name -like $p) { $skip = $true; break } }
    }
    if ($skip) { $excluded.Add($relUnix); return }

    $target = Join-Path $Destination $rel
    New-Item -ItemType Directory -Path (Split-Path -Parent $target) -Force | Out-Null
    Copy-Item $_.FullName $target
    $script:copied++
}

Write-Host ""
Write-Host "Exported $copied file(s) to $Destination"
Write-Host ""
Write-Host "Excluded ($($excluded.Count)):" -ForegroundColor Yellow
$excluded | Sort-Object | ForEach-Object { Write-Host "  $_" }

# --- ship the PUBLIC install-hooks.ps1 --------------------------------------
# The private install-hooks.ps1 pins to the private remote and is excluded above.
# Public users still need an installer (the README references it), so place the
# public-only version here under its canonical name.
$pubInstaller = Join-Path $PSScriptRoot 'hooks/public-install-hooks.ps1'
if (Test-Path $pubInstaller) {
    $installerDst = Join-Path $Destination 'scripts/install-hooks.ps1'
    New-Item -ItemType Directory -Path (Split-Path -Parent $installerDst) -Force | Out-Null
    Copy-Item $pubInstaller $installerDst -Force
    Write-Host ""
    Write-Host "Shipped public scripts/install-hooks.ps1 (private version excluded)."
}

# --- install the public repo's guard hooks ----------------------------------
# .git/hooks is not version-controlled, so a fresh clone of the public repo has
# no protection at all. Reinstalling them on every export means the guards can
# never silently go missing. Skipped when Destination is a worktree, whose .git
# is a pointer FILE, not a hooks-home directory (-PathType Container guards that).
$hookSrc = Join-Path $PSScriptRoot 'hooks'
$hookDst = Join-Path $Destination '.git/hooks'
if ((Test-Path $hookSrc) -and (Test-Path -PathType Container (Join-Path $Destination '.git'))) {
    New-Item -ItemType Directory -Path $hookDst -Force | Out-Null
    Copy-Item (Join-Path $hookSrc 'public-pre-commit') (Join-Path $hookDst 'pre-commit') -Force
    Copy-Item (Join-Path $hookSrc 'public-pre-push')   (Join-Path $hookDst 'pre-push')   -Force
    Write-Host ""
    Write-Host "Guard hooks installed into $hookDst (pre-commit, pre-push)."
}

# --- normalize the H1 title + point install instructions at the PUBLIC repo --
$readme = Join-Path $Destination 'README.md'
if (Test-Path $readme) {
    $txt = Get-Content $readme -Raw
    # The private repo is named '...-config'; the public one drops that suffix.
    # Fix the H1 whether or not -PublicRepoUrl was supplied.
    $txt = $txt -replace '(?m)^# ai-agent-orchestration-config\b', '# ai-agent-orchestration'
    if ($PublicRepoUrl) {
        $txt = [regex]::Replace($txt, 'https://github\.com/[^\s`)]+', $PublicRepoUrl)
        Write-Host ""
        Write-Host "README clone URLs rewritten to $PublicRepoUrl"
    } else {
        Write-Host ""
        Write-Host "NOTE: README still points at the private repo. Re-run with -PublicRepoUrl" -ForegroundColor Yellow
        Write-Host "      once the public repo exists, or edit it by hand before publishing." -ForegroundColor Yellow
    }
    Set-Content -Path $readme -Value $txt -NoNewline
    Write-Host "README H1 title normalized to '# ai-agent-orchestration'."
}

# --- scrub maintainer-specific literals from the exported tree --------------
# Values that are correct on the private machine but must not ship (e.g. the
# per-agent commit-identity email). Read find=replace pairs from a LOCAL file
# that is itself excluded from the export (*.local.txt), so the private values
# never appear in this script or the published tree. Format, one per line:
#   private-literal=public-placeholder
$scrubFile = Join-Path $repo 'export-scrub.local.txt'
if (Test-Path $scrubFile) {
    $pairs = @()
    foreach ($line in (Get-Content $scrubFile)) {
        $t = $line.Trim()
        if (-not $t -or $t.StartsWith('#') -or -not $t.Contains('=')) { continue }
        $i = $t.IndexOf('=')
        $pairs += ,@($t.Substring(0, $i).Trim(), $t.Substring($i + 1).Trim())
    }
    if ($pairs.Count -gt 0) {
        $scrubExt = @('.py', '.md', '.ps1', '.sh', '.txt', '.json', '.toml', '.cmd', '.yml', '.yaml')
        $scrubbed = 0
        foreach ($f in (Get-ChildItem -Path $Destination -Recurse -File)) {
            if ($scrubExt -notcontains $f.Extension.ToLower()) { continue }
            $c = Get-Content $f.FullName -Raw
            if (-not $c) { continue }
            $orig = $c
            foreach ($p in $pairs) { $c = $c.Replace($p[0], $p[1]) }
            if ($c -ne $orig) { Set-Content -Path $f.FullName -Value $c -NoNewline; $scrubbed++ }
        }
        Write-Host ""
        Write-Host "Applied $($pairs.Count) scrub-substitution(s) across $scrubbed file(s)."
    }
}

# --- last-line check: anything identifying that slipped through? ------------
Write-Host ""
Write-Host "Scanning the exported tree for identifying strings..." -ForegroundColor Cyan
# Read the terms from a LOCAL file that is itself excluded from the export.
# Hardcoding them here would defeat the purpose: the scrubbing list would publish
# the exact project names it exists to remove. Caught by this very scan.
$needles = @($env:USERNAME)
$needleFile = Join-Path $repo 'export-needles.local.txt'
if (Test-Path $needleFile) {
    $needles += (Get-Content $needleFile |
                 Where-Object { $_.Trim() -and -not $_.StartsWith('#') } |
                 ForEach-Object { $_.Trim() })
} else {
    Write-Host "  (no export-needles.local.txt - scanning for your username only)" -ForegroundColor DarkGray
}
$hits = @()
Get-ChildItem -Path $Destination -Recurse -File | ForEach-Object {
    $f = $_
    foreach ($n in $needles) {
        if ([string]::IsNullOrWhiteSpace($n)) { continue }
        if (Select-String -Path $f.FullName -Pattern ([regex]::Escape($n)) -Quiet -ErrorAction SilentlyContinue) {
            $shortPath = $f.FullName.Substring($Destination.Length).TrimStart('\', '/')
            $hits += ("  {0}  contains '{1}'" -f $shortPath, $n)
        }
    }
}
if ($hits.Count -eq 0) {
    Write-Host "  clean - no identifying strings found." -ForegroundColor Green
} else {
    Write-Host "  REVIEW THESE before publishing:" -ForegroundColor Red
    $hits | Sort-Object -Unique | ForEach-Object { Write-Host $_ }
}

Write-Host ""
if ($destIsRepo) {
    Write-Host "Nothing was published. This is what changed since the last public update:"
    Push-Location $Destination
    $status = (git status --short) -split "`n" | Where-Object { $_.Trim() }
    if ($status) {
        $status | ForEach-Object { Write-Host "  $_" }
        Write-Host ""
        Write-Host "  Review it, then:  git -C $Destination add -A; git -C $Destination commit -m '...'; git -C $Destination push"
    } else {
        Write-Host "  (no changes - the public copy is already up to date)"
    }
    Pop-Location
} else {
    Write-Host "Nothing was published. Read the tree, then create a NEW repo from it:"
    Write-Host "  cd $Destination; git init; git add -A; git commit -m 'Initial public release'"
    Write-Host "  git remote add origin <public-repo-url>; git push -u origin main"
}
